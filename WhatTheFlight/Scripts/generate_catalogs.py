#!/usr/bin/env python3
"""
Regenerates the offline airport and airline tables compiled into the app.

    python3 Scripts/generate_catalogs.py            # downloads the sources
    python3 Scripts/generate_catalogs.py --offline airports.csv airlines.dat

Sources
  * OurAirports (public domain)       https://ourairports.com/data/
  * OpenFlights airlines (ODbL 1.0)   https://openflights.org/data.html

Writes WhatTheFlight/Data/AirportCatalog+Data.swift and AirlineCatalog+Data.swift.
Hand-curated entries in AirportCatalog.swift / AirlineCatalog.swift take precedence
over these at runtime, so tidy names there rather than here.
"""

import csv
import io
import re
import sys
import urllib.request
from pathlib import Path

AIRPORTS_URL = "https://davidmegginson.github.io/ourairports-data/airports.csv"
AIRLINES_URL = "https://raw.githubusercontent.com/jpatokal/openflights/master/data/airlines.dat"
OUT = Path(__file__).resolve().parent.parent / "WhatTheFlight" / "Data"


def fetch(url: str) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": "WhatTheFlight catalog generator"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read().decode("utf-8")


def clean(text: str) -> str:
    text = (text or "").replace("|", "/").replace("\\N", "")
    text = "".join(ch for ch in text if ch.isprintable()).strip()
    return re.sub(r"\s+", " ", text)


def tidy_airport_name(name: str) -> str:
    name = clean(name)
    name = re.sub(r"\bInternational\b", "Intl", name)
    name = re.sub(r"\s+Airport$", "", name)
    return name


def airports(text: str) -> list[str]:
    keep = {"large_airport", "medium_airport", "small_airport"}
    rows = []
    for r in csv.DictReader(io.StringIO(text)):
        code = r["iata_code"].strip().upper()
        if not re.fullmatch(r"[A-Z0-9]{3}", code) or r["type"] not in keep:
            continue
        lat, lon = float(r["latitude_deg"]), float(r["longitude_deg"])
        city = clean(r["municipality"]) or clean(r["name"])
        rows.append(f"{code}|{lat:.4f}|{lon:.4f}|{city}|{tidy_airport_name(r['name'])}|{r['iso_country'].strip()}")
    return sorted(set(rows))


def airlines(text: str) -> list[str]:
    best: dict[str, tuple[bool, int, str]] = {}
    for fields in csv.reader(io.StringIO(text)):
        if len(fields) < 8:
            continue
        ident, name, _alias, iata, icao, callsign, country, active = fields[:8]
        icao = icao.strip().upper()
        if not re.fullmatch(r"[A-Z]{3}", icao):
            continue
        name = clean(name)
        if not name or name.lower() in {"unknown", "private flight"}:
            continue
        iata = iata.strip().upper()
        iata = iata if re.fullmatch(r"[A-Z0-9]{2}", iata) else ""
        line = f"{icao}|{iata}|{name}|{clean(callsign).upper()}|{clean(country)}"
        rank = (active == "Y", int(ident) if ident.lstrip("-").isdigit() else 0, line)
        # Prefer an active entry, then the most recently added one.
        if icao not in best or rank[:2] > best[icao][:2]:
            best[icao] = rank
    return sorted(v[2] for v in best.values())


def write(path: Path, type_name: str, property_name: str, header: str, lines: list[str]) -> None:
    body = "\n".join(lines)
    assert '"""#' not in body
    path.write_text(
        f"//\n//  {path.name}\n//  WhatTheFlight\n//\n//  GENERATED by Scripts/generate_catalogs.py — do not edit by hand.\n"
        f"//  {header}\n//\n\nimport Foundation\n\nextension {type_name} {{\n"
        f"    static let {property_name} = #\"\"\"\n{body}\n\"\"\"#\n}}\n",
        encoding="utf-8",
    )
    print(f"wrote {path} ({len(lines)} rows)")


def main() -> None:
    if len(sys.argv) == 4 and sys.argv[1] == "--offline":
        airport_text = Path(sys.argv[2]).read_text(encoding="utf-8")
        airline_text = Path(sys.argv[3]).read_text(encoding="utf-8")
    else:
        airport_text, airline_text = fetch(AIRPORTS_URL), fetch(AIRLINES_URL)
    write(OUT / "AirportCatalog+Data.swift", "AirportCatalog", "generatedRaw",
          "IATA|lat|lon|city|name|country — OurAirports, public domain.", airports(airport_text))
    write(OUT / "AirlineCatalog+Data.swift", "AirlineCatalog", "generatedRaw",
          "ICAO|IATA|name|radio callsign|country — OpenFlights, ODbL 1.0.", airlines(airline_text))


if __name__ == "__main__":
    main()
